#!/bin/sh
# Rootfs preparation for UFLinux device images. Runs inside the arch chroot
# after the repositories and signing key are in place, and before the disk
# image is assembled. It installs the package set, configures the installed
# (non-live) system, regenerates the initramfs without a modloop, and stages
# the boot partition contents that scripts/builder.py later copies into the
# FAT partition.
#
# Required environment: UFLINUX_DEVICE UFLINUX_ARCH UFLINUX_BOOT
# UFLINUX_SERIAL UFLINUX_CMDLINE UFLINUX_ROOT_PARTUUID UFLINUX_PACKAGES
# UFLINUX_ESP UFLINUX_VERSION UFLINUX_ROOTFS. Optional: UFLINUX_NURA_PACKAGES
# (with UFLINUX_NURA_REPOSITORY), UFLINUX_DTB, UFLINUX_DTBLOADER.
set -eu

device="$UFLINUX_DEVICE"
arch="$UFLINUX_ARCH"
boot="$UFLINUX_BOOT"
serial="$UFLINUX_SERIAL"
cmdline="$UFLINUX_CMDLINE"
root_partuuid="$UFLINUX_ROOT_PARTUUID"
esp="$UFLINUX_ESP"
version="$UFLINUX_VERSION"
rootfs="$UFLINUX_ROOTFS"

# Device images boot from an installed root, so the feature set of the ISO is
# wrong here: cdrom and raid pull in drivers no supported board uses, and
# uflinux-plymouth drags the splash into an initramfs that has nothing to show
# while the root filesystem is still being located. The root filesystem
# feature matches the one scripts/builder.py formats, so the initramfs can
# mount it without probing.
features="base $rootfs phy mmc usb scsi nvme ata virtio kms"

# The mkinitfs trigger fires on every /lib/modules change and would build an
# initramfs from the ISO feature set (and abort the transaction if that
# failed), so the trigger is disabled and the initramfs is generated below.
write_mkinitfs_conf() {
	mkdir -p /etc/mkinitfs
	cat > /etc/mkinitfs/mkinitfs.conf <<EOF
# Generated by profiles/device-rootfs.sh for the $device image.
disable_trigger=yes
features="$features"
EOF
}

write_mkinitfs_conf

# shellcheck disable=SC2086
apk add --no-progress $UFLINUX_PACKAGES

# Optional extras that only exist in the pinned Nura repository. They are
# unpacked rather than installed, and fetched with an explicit --repository so
# that no solver run ever sees Nura: it carries its own mkinitfs replacement
# (postmarketos-mkinitfs) which conflicts with the Alpine one that
# uflinux-initramfs requires, so any solver run that sees both repositories
# refuses to select packages. apk fetch resolves the file directly from the
# pinned index and tar lays it down at the package's own paths.
if [ -n "${UFLINUX_NURA_PACKAGES:-}" ]; then
	# shellcheck disable=SC2086
	for package in $UFLINUX_NURA_PACKAGES; do
		apk fetch --quiet --stdout --repository "$UFLINUX_NURA_REPOSITORY" "$package" |
			tar -C / -xz
	done
fi

# mkinitfs owns /etc/mkinitfs/mkinitfs.conf and ships no protect entry for it,
# so the package install above may have replaced the file written earlier.
write_mkinitfs_conf

# One kernel per device image; the package set is what selects it.
kversion=$(ls /lib/modules)
[ -n "$kversion" ] || {
	echo "device-rootfs: no kernel modules installed for $device" >&2
	exit 1
}
if [ "$(printf '%s\n' "$kversion" | wc -l)" != 1 ]; then
	echo "device-rootfs: expected exactly one kernel for $device, got: $kversion" >&2
	exit 1
fi
kflavor=${kversion##*-}

# The marker is what arms the first-boot partition growth; the packaged
# default says "generic" so the service stays inert on installed systems.
mkdir -p /etc/uflinux
printf '%s\n' "$device" > /etc/uflinux/device

printf '%s\n' "uflinux-$device" > /etc/hostname

# An installed system has no live-session getty, so the serial console is
# configured from the board description instead of the architecture default.
cat > /etc/inittab <<EOF
::sysinit:/sbin/openrc sysinit
::sysinit:/sbin/openrc boot
::wait:/sbin/openrc default
tty1::respawn:/sbin/getty 38400 tty1
tty2::respawn:/sbin/getty 38400 tty2
$serial::respawn:/sbin/getty -L 115200 $serial vt100
# Stuff to do for the 3-finger-virtue key sequence.
# NOTE: all of the below must be on one line
::ctrlaltdel:/sbin/reboot
::shutdown:/sbin/openrc shutdown
EOF

# OpenRC does not enable services on install, so the boot order is written
# out here. It matches the ISO profile minus the live-session plumbing
# (modloop, splash handoff, uflinux-live) plus the device resize service.
# Not called "enable": ShellCheck reserves that name for the bash builtin and
# reports SC3044 in a POSIX sh script.
enable_service() {
	runlevel="$1"
	shift
	mkdir -p "/etc/runlevels/$runlevel"
	for service in "$@"; do
		[ -e "/etc/init.d/$service" ] || continue
		ln -sf "/etc/init.d/$service" "/etc/runlevels/$runlevel/$service"
	done
}

enable_service sysinit devfs dmesg udev udev-trigger udev-settle hwdrivers
enable_service boot hwclock modules sysctl hostname bootmisc syslog uflinux-device
enable_service default dbus elogind iwd connman tlp uflinux-acpid uflinux-routes greetd
enable_service shutdown killprocs mount-ro

# The initramfs is built by hand rather than through update-kernel: the
# --media option that update-kernel always passes is what produces the
# squashfs modloop, and a device image has no modloop.
rm -f "/boot/initramfs-$kflavor"
# shellcheck disable=SC2086
/sbin/mkinitfs -q -b / -C zstd -F "$features" \
	-i /project/aports/uflinux/uflinux-initramfs-init \
	-o "/boot/initramfs-$kflavor" "$kversion"

# The boot partition is staged as a plain directory so that the image
# assembly step stays independent of the boot scheme.
mkdir -p "$esp/boot"
kernel_image="/boot/vmlinuz-$kversion"
[ -f "$kernel_image" ] || kernel_image="/boot/vmlinuz-$kflavor"
[ -f "$kernel_image" ] || {
	echo "device-rootfs: no kernel image for $device" >&2
	exit 1
}
cp -a "$kernel_image" "$esp/boot/vmlinuz"
cp -a "/boot/initramfs-$kflavor" "$esp/boot/initramfs"

# Board device trees travel with the kernel package. The generic kernel keeps
# them in vendor subdirectories, the Raspberry Pi kernel ships them next to
# the kernel image together with the overlays the firmware expects.
if [ -d /boot/dtbs-lts ]; then
	mkdir -p "$esp/dtbs"
	cp -a /boot/dtbs-lts/. "$esp/dtbs/"
fi
if [ -d /boot/overlays ]; then
	mkdir -p "$esp/overlays"
	cp -a /boot/overlays/. "$esp/overlays/"
	cp -a /boot/*.dtb "$esp/"
fi

# The root is found by partition UUID rather than device name, and has to be
# mounted read-write because nothing runs the live-session switch to rw. Its
# type is stated explicitly so the kernel does not have to guess, which also
# matches the single filesystem feature in the initramfs. The framebuffer
# console comes first so that boards with a display are usable even when the
# serial console is not wired up.
rootargs="root=PARTUUID=$root_partuuid rootwait rootfstype=$rootfs rootflags=rw"
case "$cmdline" in
*console=*) consoleargs="" ;;
*) consoleargs=" console=tty0 console=$serial,115200n8" ;;
esac

case "$boot" in
efi)
	# systemd-boot ships as a bare EFI binary; the install step that would
	# copy it onto a real ESP needs firmware variables, so it is copied here.
	case "$arch" in
	aarch64) suffix=aa64;;
	x86_64) suffix=x64;;
	*) echo "device-rootfs: no systemd-boot binary for $arch" >&2; exit 1;;
	esac
	installer_efi="/usr/lib/systemd/boot/efi/systemd-boot$suffix.efi"
	[ -f "$installer_efi" ] || {
		echo "device-rootfs: missing $installer_efi" >&2
		exit 1
	}
	mkdir -p "$esp/EFI/boot" "$esp/loader/entries"
	cp -a "$installer_efi" "$esp/EFI/boot/boot$suffix.efi"
	printf 'timeout 3\n' > "$esp/loader/loader.conf"
	{
		printf 'title\tUFLinux %s (%s)\n' "$version" "$device"
		printf 'linux\t/boot/vmlinuz\n'
		printf 'initrd\t/boot/initramfs\n'
		printf 'options\t%s%s %s\n' "$cmdline" "$consoleargs" "$rootargs"
	} > "$esp/loader/entries/uflinux.conf"

	# QCOM boards have no firmware-provided device tree on some models, so
	# the Nura dtbloader EFI driver installs one from this partition before
	# the boot entry runs. The builder points at the file only for boards
	# that ship the driver, so that the path is not guessed here.
	if [ -n "${UFLINUX_DTBLOADER:-}" ]; then
		[ -f "$UFLINUX_DTBLOADER" ] || {
			echo "device-rootfs: dtbloader $UFLINUX_DTBLOADER is missing" >&2
			exit 1
		}
		mkdir -p "$esp/EFI/systemd/drivers"
		cp -a "$UFLINUX_DTBLOADER" \
			"$esp/EFI/systemd/drivers/dtbloader$suffix.efi"
	fi
	;;
rpi)
	# The VideoCore firmware reads the kernel, initramfs, device tree and
	# overlays from this FAT partition, so everything has to be reachable
	# from its root with the paths used in config.txt.
	printf '%s\n' \
		'disable_splash=1' \
		'disable_overscan=1' \
		'arm_64bit=1' \
		'enable_uart=1' \
		'kernel=boot/vmlinuz' \
		'initramfs boot/initramfs followkernel' \
		'include usercfg.txt' > "$esp/config.txt"
	printf 'UFLinux board overrides. This file is not replaced on upgrade.\n' \
		> "$esp/usercfg.txt"
	printf '%s%s %s\n' "$cmdline" "$consoleargs" "$rootargs" > "$esp/cmdline.txt"

	# The firmware blobs are packaged for an update tool rather than for a
	# boot partition layout, so they are unpacked straight out of the APKs.
	for package in raspberrypi-bootloader-common raspberrypi-bootloader; do
		apk fetch --quiet --stdout "$package" |
			tar -C "$esp" -xz --strip=1 boot/
	done
	;;
extlinux)
	# U-Boot distro boot reads this file, so the board's existing bootloader
	# is reused instead of shipping a second stage.
	[ -n "${UFLINUX_DTB:-}" ] || {
		echo "device-rootfs: $device needs a device tree path for extlinux" >&2
		exit 1
	}
	[ -f "$esp/dtbs/$UFLINUX_DTB" ] || {
		echo "device-rootfs: $esp/dtbs/$UFLINUX_DTB is missing" >&2
		exit 1
	}
	mkdir -p "$esp/extlinux"
	{
		printf 'TIMEOUT 30\n'
		printf 'DEFAULT uflinux\n'
		printf 'LABEL uflinux\n'
		printf '\tMENU LABEL UFLinux %s (%s)\n' "$version" "$device"
		printf '\tLINUX /boot/vmlinuz\n'
		printf '\tINITRD /boot/initramfs\n'
		printf '\tFDT /dtbs/%s\n' "$UFLINUX_DTB"
		printf '\tAPPEND %s%s %s\n' "$cmdline" "$consoleargs" "$rootargs"
	} > "$esp/extlinux/extlinux.conf"
	;;
*)
	echo "device-rootfs: unsupported boot mode $boot" >&2
	exit 1
	;;
esac
